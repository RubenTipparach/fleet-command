#!/usr/bin/env python3
"""Write a faction's battle console page from the one source page, so every faction's console runs the same code
(CLAUDE.md section 6.1; openspec/changes/krai-battle-console). The source is docs/mockups/battle-console.html (the
Concord skin); a faction's page differs only in what it names here: its skin id (the page's <meta name="fc-skin">,
the skin its player side wears) and its title. Every skin's library, kit and type are in the source page already (the
console follows the ship you command; openspec/changes/fleet-skins). Everything else, every rule, panel and control, is
copied as it is.

    python3 tools/mockups/skin_page.py krai            # writes docs/mockups/battle-console-krai.html
    python3 tools/mockups/skin_page.py krai --check    # exit 1 if that page is not what this would write

The written page is a build product: edit the source page or the skin's library, then run this again.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import inline_data  # noqa: E402  (fills the INLINE markers)

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/mockups/battle-console.html"

SKINS = {
    "krai": {
        "title": "Krai Battle Console",
        "what": "Mockup 8: the battle console in the Krai Warhost skin (OpenSpec change krai-battle-console)",
    },
    "ssarith": {
        "title": "Ssarith Battle Console",
        "what": "Mockup 15: the battle console in the Ssarith Hunt skin (OpenSpec change ssarith-battle-console)",
    },
    "kelvane": {
        "title": "Kelvane Battle Console",
        "what": "Mockup 20: the battle console in the Kelvane Institute skin (OpenSpec change kelvane-battle-console)",
    },
    "aelith": {
        "title": "Aelith Battle Console",
        "what": "Mockup 31: the battle console in the Aelith Conclave skin (OpenSpec change aelith-battle-console)",
    },
    "ombrai": {
        "title": "Ombrai Battle Console",
        "what": "Mockup 32: the battle console in the Ombrai skin (OpenSpec change ombrai-battle-console)",
    },
    "vhorr": {
        "title": "Vhorr Battle Console",
        "what": "Mockup 33: the battle console in the Vhorr Brood skin (OpenSpec change vhorr-battle-console)",
    },
}
# Every skin's library, kit and type are inlined in the source page itself (openspec/changes/fleet-skins: the console
# follows the ship you command, so one page carries every skin); a faction's page differs only in its meta, title and
# header.


def swap(text, old, new):
    """Replace one exact occurrence, or stop: a source page that no longer has the anchor must be looked at."""
    if text.count(old) != 1:
        raise SystemExit(f"skin_page: expected one {old[:60]!r} in {SOURCE.name}, found {text.count(old)}")
    return text.replace(old, new)


def build(skin_id):
    s = SKINS[skin_id]
    t = SOURCE.read_text()
    t = swap(t, "<!doctype html>\n<!--\n", "<!doctype html>\n<!--\n  " + s["what"] + ".\n"
             "  WRITTEN BY tools/mockups/skin_page.py FROM docs/mockups/battle-console.html: do not edit this file; edit the source\n"
             "  page or the skin's library and run the script again. The source's own notes follow.\n\n")
    t = swap(t, '<meta name="viewport"', f'<meta name="fc-skin" content="{skin_id}">\n<meta name="viewport"')
    t = swap(t, "<title>Battle Console</title>", f"<title>{s['title']}</title>")
    return inline_data.fill(t)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if not args or args[0] not in SKINS:
        raise SystemExit(f"usage: skin_page.py <{'|'.join(SKINS)}> [--check]")
    skin_id = args[0]
    out = ROOT / f"docs/mockups/battle-console-{skin_id}.html"
    page = build(skin_id)
    if check:
        if not out.exists() or out.read_text() != page:
            print(f"{out.relative_to(ROOT)} is stale: run tools/mockups/skin_page.py {skin_id}")
            sys.exit(1)
        print(f"{out.relative_to(ROOT)} is current")
        return
    out.write_text(page)
    print(f"wrote {out.relative_to(ROOT)} ({len(page) // 1024} KiB)")


if __name__ == "__main__":
    main()
