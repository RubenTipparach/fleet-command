#!/usr/bin/env python3
"""Write the Space Chart page from mockup 1, so the chart runs the same code as the game flow (CLAUDE.md section 6.1;
openspec/changes/paper-map). The source is docs/mockups/game-flow.html. The chart page differs only in what this script
names: its <meta name="fc-start" content="chart"> (the source's startAt() then opens the campaign map at once, the saved
Concord campaign if there is one), its title, and its corner badge, which links back to the tracker (CLAUDE.md section 4;
the source itself carries no tracker link, section 14). Every rule, screen and control is copied as it is.

    python3 tools/mockups/chart_page.py            # writes docs/mockups/space-chart.html
    python3 tools/mockups/chart_page.py --check    # exit 1 if that page is not what this would write

The written page is a build product: edit the source page, then run this again.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/mockups/game-flow.html"
OUT = ROOT / "docs/mockups/space-chart.html"
TRACKER_URL = "https://claude.ai/artifact/8VqA9YjhCrgoiY2CGR1Qxu"


def swap(text, old, new):
    """Replace one exact occurrence, or stop: a source page that no longer has the anchor must be looked at."""
    if text.count(old) != 1:
        raise SystemExit(f"chart_page: expected one {old[:60]!r} in {SOURCE.name}, found {text.count(old)}")
    return text.replace(old, new)


def build():
    t = SOURCE.read_text()
    t = swap(t, "<title>Fleet Command Game Flow</title>",
             "<title>Fleet Command Space Chart</title>\n"
             "<!-- Mockup 24: the campaign's space chart, opened straight onto the paper map (OpenSpec change paper-map).\n"
             "     WRITTEN BY tools/mockups/chart_page.py FROM docs/mockups/game-flow.html: do not edit this file; edit the\n"
             "     source page and run the script again. -->\n"
             '<meta name="fc-start" content="chart">')
    t = swap(t, '<div class="badge">Mockup 1 · game-flow</div>',
             '<div class="badge">Mockup 24 · space chart · '
             f'<a href="{TRACKER_URL}" target="_blank" rel="noopener" style="color: inherit; pointer-events: auto;">'
             'All Fleet Command mockups (the tracker)</a></div>')
    return t


def main():
    page = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != page:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/mockups/chart_page.py")
            sys.exit(1)
        print(f"{OUT.relative_to(ROOT)} is current")
        return
    OUT.write_text(page)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(page) // 1024} KiB)")


if __name__ == "__main__":
    main()
