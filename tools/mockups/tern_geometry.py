#!/usr/bin/env python3
"""Copy the SCS Tern's geometry (and nothing else) from Star Crew Bridge Simulator into mockup 6.

Owner, 2026-11-03: "we are using the wrong tern model, I'd like to use the latest tern model, but with our standard texture,
instead of the custom texture the tern is using right now in star crew repo". So the page takes the latest tern.glb's
positions, normals and triangle indices, one part per material, and paints them with its own shader; the glb's textures,
UVs and vertex colours are left behind.

Source: RubenTipparach/star-crew-bridge-simulator, assets/models/exteriors/tern.glb (axes +X port, +Y dorsal, +Z bow,
metres). The page records the source revision beside the data.

    python3 tools/mockups/tern_geometry.py <star-crew-checkout> docs/mockups/concord-hull-concepts.html
"""
import base64, json, pathlib, struct, subprocess, sys

BEGIN, END = '// TERN-GEOMETRY-BEGIN', '// TERN-GEOMETRY-END'


def read_glb(path):
    d = path.read_bytes()
    jlen = struct.unpack('<I', d[12:16])[0]
    j = json.loads(d[20:20 + jlen])
    off = 20 + jlen
    blen = struct.unpack('<I', d[off:off + 4])[0]
    return j, d[off + 8:off + 8 + blen]


def accessor(j, b, i):
    a = j['accessors'][i]
    v = j['bufferViews'][a['bufferView']]
    start = v.get('byteOffset', 0) + a.get('byteOffset', 0)
    comps = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}[a['type']]
    fmt = {5126: 'f', 5123: 'H', 5125: 'I', 5121: 'B'}[a['componentType']]
    size = struct.calcsize(fmt)
    stride = v.get('byteStride', size * comps)
    out = []
    for k in range(a['count']):
        out.extend(struct.unpack_from('<' + fmt * comps, b, start + k * stride))
    return out, fmt


def main():
    repo, page = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    glb = repo / 'assets/models/exteriors/tern.glb'
    rev = subprocess.run(['git', '-C', str(repo), 'log', '-1', '--format=%h', '--', str(glb.relative_to(repo))], capture_output=True, text=True).stdout.strip()
    j, b = read_glb(glb)
    node = j['nodes'][0]
    assert not any(k in node for k in ('translation', 'rotation', 'scale', 'matrix')), 'the Tern node carries a transform; this copy assumes none'
    parts = {}
    for p in j['meshes'][node['mesh']]['primitives']:
        name = j['materials'][p['material']]['name']
        pos, _ = accessor(j, b, p['attributes']['POSITION'])
        nor, _ = accessor(j, b, p['attributes']['NORMAL'])
        idx, _ = accessor(j, b, p['indices'])
        parts[name] = {
            'pos': base64.b64encode(struct.pack('<%df' % len(pos), *pos)).decode(),
            'nor': base64.b64encode(struct.pack('<%df' % len(nor), *nor)).decode(),
            'idx': base64.b64encode(struct.pack('<%dI' % len(idx), *idx)).decode(),
        }
    block = (f"{BEGIN}\n// Generated by tools/mockups/tern_geometry.py from star-crew-bridge-simulator {rev}, assets/models/exteriors/tern.glb:\n"
             f"// geometry only (positions, normals, indices per material part); painted here with the page's own shader.\n"
             f"const TERN_GLB = {{ rev: '{rev}', parts: {json.dumps(parts, separators=(',', ':'))} }};\n{END}")
    s = page.read_text()
    a, z = s.index(BEGIN), s.index(END) + len(END)
    page.write_text(s[:a] + block + s[z:])
    print(f'{page}: Tern geometry from {rev}, parts {", ".join(parts)}; {sum(len(v["pos"]) + len(v["nor"]) + len(v["idx"]) for v in parts.values())} characters')


if __name__ == '__main__':
    main()
